"""Render the schema inventory half of `docs/dev/schema-contract.md`.

Model-driven: reads `Base.metadata` (never a live database), so the output is
deterministic and cannot drift from the models.
"""

from sqlalchemy import CheckConstraint, Table

from ..storage.db import Base
from . import schema_contract


def _cell(value: str) -> str:
    return value.replace("|", "\\|") or "—"


def _identity(table: Table) -> str:
    columns = sorted(table.primary_key.columns, key=lambda c: c.name)
    return ", ".join(f"`{c.name}` {c.type}" for c in columns)


def _foreign_keys(table: Table) -> str:
    parts: list[str] = []
    for constraint in sorted(
        table.foreign_key_constraints,
        key=lambda c: (
            tuple(sorted(element.parent.name for element in c.elements)),
            c.ondelete or "",
            c.name or "",
        ),
    ):
        pairs = ", ".join(
            f"`{element.parent.name}`→`{element.column.table.name}.{element.column.name}`"
            for element in sorted(constraint.elements, key=lambda e: e.parent.name)
        )
        ondelete = constraint.ondelete or "NO ACTION"
        parts.append(f"{pairs} ON DELETE {ondelete} ({constraint.name or 'unnamed'})")
    return "<br>".join(parts) if parts else "—"


def _indexes(table: Table) -> str:
    parts: list[str] = []
    for index in sorted(table.indexes, key=lambda i: i.name or ""):
        flags = []
        if index.unique:
            flags.append("unique")
        if index.dialect_options["sqlite"].get("where") is not None:
            flags.append("partial")
        suffix = f" [{', '.join(flags)}]" if flags else ""
        columns = ", ".join(c.name for c in index.columns)
        parts.append(f"`{index.name}`({columns}){suffix}")
    return "<br>".join(parts) if parts else ""


def _checks(table: Table) -> str:
    parts = [
        f"`{constraint.name or 'unnamed'}`: {constraint.sqltext}"
        for constraint in sorted(table.constraints, key=lambda c: str(c.name or ""))
        if isinstance(constraint, CheckConstraint)
    ]
    return "<br>".join(parts)


def render() -> str:
    tables = sorted(Base.metadata.tables.values(), key=lambda t: t.name)
    rows: list[str] = [
        "<!-- generated by scripts/schema_inventory.py — do not edit by hand "
        f"({len(tables)} tables) -->",
        "",
        "| Table | Identity | Profile scope | Foreign keys | Closed sets (CHECK) "
        "| JSON columns (species) | Indexes & checks |",
        "|---|---|---|---|---|---|---|",
    ]
    for table in tables:
        closed = [
            f"`{key.split('.', 1)[1]}` → {enum.__name__}"
            for key, enum in sorted(schema_contract.CLOSED_SETS.items())
            if key.startswith(f"{table.name}.")
        ]
        json_columns = [
            f"`{key.split('.', 1)[1]}` ({species})"
            for key, species in sorted(schema_contract.JSON_SPECIES.items())
            if key.startswith(f"{table.name}.")
        ]
        checks = _checks(table)
        indexes = _indexes(table)
        structural = indexes
        if checks:
            structural = f"{structural}<br>CHECKs: {checks}" if structural else f"CHECKs: {checks}"
        rows.append(
            "| "
            + " | ".join(
                [
                    f"`{table.name}`",
                    _cell(_identity(table)),
                    _cell(schema_contract.PROFILE_SCOPE.get(table.name, "—")),
                    _cell(_foreign_keys(table)),
                    _cell("<br>".join(closed)),
                    _cell("<br>".join(json_columns)),
                    _cell(structural),
                ]
            )
            + " |"
        )
    return "\n".join(rows)
